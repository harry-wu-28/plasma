#!/usr/bin/env python3
"""Generate the numerics-scan inputs from the baseline two-stream input.

Writes runs/scan/inputs/<tag>.toml plus runs/scan/inputs/manifest.txt
("<tag> <shape_order> <input path>" per line), which the SLURM array script reads.
Each variant changes exactly ONE knob relative to the baseline, so every effect
can be attributed:

  ppc*   particles per cell (ppc0)          -> noise floor / seed amplitude
  filt*  current_filters passes             -> smoothing of short-k noise, damping
  res*   cells (total particle count held fixed by raising ppc0) -> grid heating as
         lambda_D/dx drops below ~1 (finite-grid instability)
  shape* compile-time shape order (needs build_twostream.sh with SHAPE_ORDER=N)

Baseline: 12288 cells, ppc0 = 16, current_filters = 4, shape order 1.
Edits are textual so the baseline's comments survive; re-run after editing it.
Usage:  python runs/scan/make_scan.py
"""

import re
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASE = HERE.parent / "baseline" / "inputs" / "twostream_baseline.toml"
OUT = HERE / "inputs"

BASE_CELLS = 12288
BASE_PPC = 16.0

# tag -> (changes, shape_order)
VARIANTS = {
    "ppc4": ({"ppc0": 4.0}, 1),
    "ppc64": ({"ppc0": 64.0}, 1),
    "ppc256": ({"ppc0": 256.0}, 1),
    "filt0": ({"current_filters": 0}, 1),
    "filt1": ({"current_filters": 1}, 1),
    "filt16": ({"current_filters": 16}, 1),
    # total particles fixed: ppc0 * cells = 16 * 12288
    "res3072": ({"cells": 3072, "ppc0": BASE_PPC * BASE_CELLS / 3072}, 1),
    "res768": ({"cells": 768, "ppc0": BASE_PPC * BASE_CELLS / 768}, 1),
    "res192": ({"cells": 192, "ppc0": BASE_PPC * BASE_CELLS / 192}, 1),
    "shape3": ({}, 3),
}


def sub_once(pattern, repl, text):
    new, n = re.subn(pattern, repl, text, count=1, flags=re.M)
    if n != 1:
        raise RuntimeError(f"pattern not found in baseline: {pattern}")
    return new


def make(tag, changes, text):
    text = sub_once(r'^(\s*name\s*=\s*)"[^"]*"', rf'\g<1>"twostream_{tag}"', text)
    if "ppc0" in changes:
        text = sub_once(r"^(\s*ppc0\s*=\s*)[\d.eE+-]+", rf"\g<1>{changes['ppc0']:.1f}", text)
    if "current_filters" in changes:
        text = sub_once(r"^(\s*current_filters\s*=\s*)\d+",
                        rf"\g<1>{changes['current_filters']}", text)
    if "cells" in changes:
        text = sub_once(r"^(\s*resolution\s*=\s*)\[\d+\]", rf"\g<1>[{changes['cells']}]", text)
    header = f"# SCAN VARIANT '{tag}' (generated by make_scan.py; do not edit by hand)\n"
    header += f"# changes vs baseline: {changes or 'none (binary differs)'}\n"
    return header + text


def main():
    base_text = BASE.read_text()
    base = tomllib.loads(base_text)
    OUT.mkdir(exist_ok=True)
    lines = []
    for tag, (changes, shape) in VARIANTS.items():
        text = make(tag, changes, base_text)
        cfg = tomllib.loads(text)  # validates the edit
        cells = cfg["grid"]["resolution"][0]
        ppc = cfg["particles"]["ppc0"]
        # densities[i] is the pair total, split evenly -> per species densities[0]/2
        npart_sp = cells * ppc * cfg["setup"]["densities"][0] / 2
        maxn = min(float(s["maxnpart"]) for s in cfg["particles"]["species"])
        if npart_sp > maxn:
            raise RuntimeError(f"{tag}: {npart_sp:.3g} particles/species > maxnpart {maxn:.3g}")
        path = OUT / f"{tag}.toml"
        path.write_text(text)
        dx = base["grid"]["extent"][0][1] / cells
        # lambda_D = v_th / omega_pe, omega_pe from the total electron density
        n_e = sum(cfg["setup"]["densities"]) / 2
        lam_d = cfg["setup"]["temperatures"][0] ** 0.5 * cfg["scales"]["skindepth0"] / n_e**0.5
        print(f"{tag:8s} cells={cells:6d} ppc0={ppc:7.1f} filters="
              f"{cfg['algorithms']['current_filters']:2d} shape={shape} "
              f"lambda_D/dx={lam_d / dx:6.2f}")
        lines.append(f"{tag} {shape} twostream/runs/scan/inputs/{tag}.toml")
    (OUT / "manifest.txt").write_text("\n".join(lines) + "\n")
    print(f"wrote {len(lines)} inputs + manifest.txt to {OUT}")


if __name__ == "__main__":
    main()
